"""Wallpaper page for awww (formerly swww). awww has no config file, so we run it ourselves and,
optionally, generate a startup script that Hyprland launches."""
from __future__ import annotations

import os
import random
import shlex
import shutil
import stat
import time
from pathlib import Path
from typing import Any

from PySide6.QtCore import Qt, Signal
from PySide6.QtGui import QPainter, QPainterPath, QPixmap
from PySide6.QtWidgets import QPushButton, QWidget

from .. import util
from ..hypr.model import HyprModel
from ..ui.widgets import (BoolControl, ColorControl, Control, EnumControl, NumberControl, Page, PickerControl,
                          SettingRow, TextControl, note, primary_button)

IMG_EXT = {".png", ".jpg", ".jpeg", ".gif", ".webp", ".bmp", ".tiff", ".tga", ".pnm", ".farbfeld", ".ff"}
DEFAULTS: dict[str, Any] = {
    "source": "image", "image": "", "folder": "", "resize": "crop", "fill": "000000ff", "filter": "Lanczos3",
    "outputs": "", "type": "simple", "duration": 3.0, "fps": 30, "step": 90, "angle": 45, "pos": "center",
    "bezier": ".54,0,.34,.99", "wave": "20,20", "invert_y": False, "autostart": False,
}
TRANSITIONS = ("simple", "fade", "left", "right", "top", "bottom", "wipe", "wave", "grow", "center", "any", "outer",
               "random", "none")


def find_binary() -> tuple[str, str] | None:
    """(client, daemon) for awww, falling back to its former name swww."""
    for name in ("awww", "swww"):
        if shutil.which(name) and shutil.which(f"{name}-daemon"):
            return name, f"{name}-daemon"
    return None


def pick_image(cfg: dict[str, Any]) -> str:
    if cfg["source"] == "folder":
        d = Path(cfg["folder"]).expanduser()
        files = [p for p in d.iterdir() if p.suffix.lower() in IMG_EXT] if d.is_dir() else []
        return str(random.choice(files)) if files else ""
    return cfg["image"]


def build_args(binary: str, cfg: dict[str, Any], image: str) -> list[str]:
    a = [binary, "img", image, "--resize", cfg["resize"]]
    if cfg["resize"] in ("fit", "no"):
        a += ["--fill-color", cfg["fill"][:6]]
    a += ["--filter", cfg["filter"], "--transition-type", cfg["type"], "--transition-duration", f"{cfg['duration']:g}",
          "--transition-fps", str(cfg["fps"]), "--transition-step", str(cfg["step"]),
          "--transition-angle", str(cfg["angle"]), "--transition-pos", cfg["pos"] or "center",
          "--transition-bezier", cfg["bezier"] or DEFAULTS["bezier"]]
    if cfg["type"] == "wave":
        a += ["--transition-wave", cfg["wave"] or DEFAULTS["wave"]]
    if cfg["invert_y"]:
        a.append("--invert-y")
    if cfg["outputs"].strip():
        a += ["--outputs", cfg["outputs"].strip()]
    return a


def startup_script(client: str, daemon: str, cfg: dict[str, Any]) -> str:
    q = shlex.quote
    lines = ["#!/bin/sh", "# Generated by Hyprtune (Wallpaper page). Rewritten whenever you press Save there.",
             f"pgrep -x {q(daemon)} >/dev/null 2>&1 || {q(daemon)} >/dev/null 2>&1 &",
             f'i=0; while [ "$i" -lt 50 ]; do {q(client)} query >/dev/null 2>&1 && break; i=$((i+1)); sleep 0.1; done']
    pre = build_args(client, cfg, "@IMG@")
    if cfg["source"] == "folder":
        names = " -o ".join(f"-iname '*{e}'" for e in sorted(IMG_EXT))
        lines.append(f"IMG=$(find {q(os.path.expanduser(cfg['folder']))} -maxdepth 1 -type f \\( {names} \\) | shuf -n 1)")
        lines.append('[ -n "$IMG" ] || exit 0')
        cmd = " ".join('"$IMG"' if x == "@IMG@" else q(x) for x in pre)
    else:
        cmd = " ".join(q(cfg["image"] if x == "@IMG@" else x) for x in pre)
    lines.append("exec " + cmd)
    return "\n".join(lines) + "\n"


class WallpaperPreview(QWidget):
    def __init__(self) -> None:
        super().__init__()
        self.setFixedHeight(246)
        self.pix: QPixmap | None = None

    def set_image(self, path: str) -> None:
        pm = QPixmap(path) if path and Path(path).is_file() else QPixmap()
        self.pix = pm if not pm.isNull() else None
        self.update()

    def paintEvent(self, _e: Any) -> None:  # noqa: N802
        p = QPainter(self)
        p.setRenderHint(QPainter.Antialiasing)
        pal = self.palette()
        p.fillRect(self.rect(), pal.color(pal.ColorRole.AlternateBase))
        p.setPen(pal.color(pal.ColorRole.Mid))
        p.drawLine(0, self.height() - 1, self.width(), self.height() - 1)
        sh = self.height() - 36.0
        sw = sh * 16 / 9
        x, y = (self.width() - sw) / 2, 18.0
        path = QPainterPath()
        path.addRoundedRect(x, y, sw, sh, 9, 9)
        p.setClipPath(path)
        if self.pix:
            scaled = self.pix.scaled(int(sw), int(sh), Qt.KeepAspectRatioByExpanding, Qt.SmoothTransformation)
            p.drawPixmap(int(x + (sw - scaled.width()) / 2), int(y + (sh - scaled.height()) / 2), scaled)
        else:
            p.fillPath(path, pal.color(pal.ColorRole.Button))
            p.setClipping(False)
            p.setPen(pal.color(pal.ColorRole.PlaceholderText))
            p.drawText(int(x), int(y), int(sw), int(sh), Qt.AlignCenter, "No wallpaper chosen")


class AwwwPage(Page):
    message = Signal(str, bool)

    def __init__(self, state: util.AppState, model: HyprModel) -> None:
        self.preview = WallpaperPreview()
        super().__init__("Wallpaper", "Pick a wallpaper and how awww transitions to it.", self.preview)
        self.state, self.model = state, model
        self.cfg: dict[str, Any] = {**DEFAULTS, **state.get("awww", {})}
        self.bin = find_binary()
        self.rows: dict[str, tuple[SettingRow, Control]] = {}
        self.script_path = util.app_dir() / "awww-startup.sh"
        self.apply_btn = primary_button("Apply now")
        self.apply_btn.clicked.connect(self.apply_now)
        self.save_btn = QPushButton("Save")
        self.save_btn.clicked.connect(self.save)
        self.actions.addWidget(self.save_btn)
        self.actions.addWidget(self.apply_btn)
        if not self.bin:
            self.add_widget(note("awww wasn't found on your PATH. Install it (for example `pacman -S awww`) and "
                                 "restart Hyprtune. Settings below are still saved for later.", True))
            self.apply_btn.setEnabled(False)

        s = self.add_section("Wallpaper")
        self._add(s, "source", "Source", "A single image, or a random one from a folder each time it's applied.",
                  EnumControl((("image", "Single image"), ("folder", "Random from folder"))))
        self._add(s, "image", "Image", "PNG, JPEG, GIF (animated), WebP and more.",
                  PickerControl("file", "No image chosen", "Images (*.png *.jpg *.jpeg *.gif *.webp *.bmp *.tiff)"))
        self._add(s, "folder", "Folder", "", PickerControl("dir", "No folder chosen"))
        s = self.add_section("Display")
        self._add(s, "resize", "Fit image to screen", "Crop fills the screen; fit keeps the whole image.",
                  EnumControl((("crop", "Crop to fill"), ("fit", "Fit inside"), ("stretch", "Stretch"), ("no", "Original size"))))
        self._add(s, "fill", "Padding colour", "Shown around the image when it doesn't fill the screen.",
                  ColorControl(False, alpha=False))
        self._add(s, "filter", "Scaling filter", "Lanczos3 looks best; nearest is for pixel art.",
                  EnumControl(tuple((f, f) for f in ("Nearest", "Bilinear", "CatmullRom", "Mitchell", "Lanczos3"))))
        self._add(s, "outputs", "Monitors", "Comma-separated names such as DP-1,HDMI-A-1. Empty means all.",
                  TextControl("All monitors"))
        s = self.add_section("Transition")
        self._add(s, "type", "Effect", "", EnumControl(tuple((t, t.capitalize()) for t in TRANSITIONS)))
        self._add(s, "duration", "Duration (seconds)", "", NumberControl(False, 0.0, 10.0, 0.1))
        self._add(s, "fps", "Frame rate", "", NumberControl(True, 1, 255))
        self._add(s, "step", "Step", "How fast pixels move toward the new image (1-255).", NumberControl(True, 1, 255))
        self._add(s, "angle", "Angle", "For the wipe and wave effects.", NumberControl(True, 0, 360))
        self._add(s, "pos", "Origin", "For grow and outer: center, top-left, 0.5,0.5 or pixels like 960,540.", TextControl("center"))
        self._add(s, "bezier", "Easing curve", "Four numbers; try values from cubic-bezier.com.", TextControl(DEFAULTS["bezier"]))
        self._add(s, "wave", "Wave size", "Width,height of the wave effect.", TextControl(DEFAULTS["wave"]))
        self._add(s, "invert_y", "Invert Y origin", "Count the origin from the top instead of the bottom.", BoolControl())
        s = self.add_section("Startup")
        self._add(s, "autostart", "Set wallpaper when Hyprland starts",
                  f"Generates {self.script_path} and launches it from Hyprtune's Hyprland settings file.", BoolControl())
        self.finish()
        self.preview.set_image(pick_image(self.cfg) if self.cfg["source"] == "image" else "")
        self._visibility()

    def _add(self, sec: Any, key: str, title: str, desc: str, ctrl: Control) -> None:
        row = SettingRow(title, desc, ctrl)
        ctrl.set_value(self.cfg[key])
        row.set_modified(self.cfg[key] != DEFAULTS[key])
        ctrl.changed.connect(lambda v, k=key, r=row: self._changed(k, v, r))
        row.resetRequested.connect(lambda k=key, r=row, c=ctrl: self._changed(k, DEFAULTS[k], r, c))
        sec.add_row(row)
        self.rows[key] = (row, ctrl)

    def _changed(self, key: str, value: Any, row: SettingRow, ctrl: Control | None = None) -> None:
        if ctrl is not None:
            ctrl.set_value(value)
        self.cfg[key] = value
        row.set_modified(value != DEFAULTS[key])
        if key in ("image", "source", "folder"):
            self.preview.set_image(self.cfg["image"] if self.cfg["source"] == "image" else "")
        self._visibility()

    def _visibility(self) -> None:
        src, typ = self.cfg["source"], self.cfg["type"]
        show = {"image": src == "image", "folder": src == "folder", "fill": self.cfg["resize"] in ("fit", "no"),
                "angle": typ in ("wipe", "wave"), "pos": typ in ("grow", "outer"), "wave": typ == "wave"}
        for k, (row, _c) in self.rows.items():
            if k in show:
                row.setVisible(show[k])

    def _daemon_ready(self) -> bool:
        assert self.bin
        client, daemon = self.bin
        if util.run([client, "query"], 2)[0] == 0:
            return True
        util.spawn_detached([daemon])
        for _ in range(30):
            time.sleep(0.1)
            if util.run([client, "query"], 2)[0] == 0:
                return True
        return False

    def apply_now(self) -> None:
        if not self.bin:
            return
        image = pick_image(self.cfg)
        if not image or not Path(image).is_file():
            self.message.emit("Choose an image (or a folder that contains images) first.", True)
            return
        if not self._daemon_ready():
            self.message.emit(f"Couldn't start {self.bin[1]}. Is a Wayland session running?", True)
            return
        rc, out, err = util.run(build_args(self.bin[0], self.cfg, image), timeout=30)
        self.message.emit("Wallpaper applied." if rc == 0 else f"{self.bin[0]} failed: {err or out}", rc != 0)

    def save(self) -> None:
        self.state.set("awww", self.cfg)
        cmd = str(self.script_path)
        if self.cfg["autostart"] and self.bin and (self.cfg["image"] or self.cfg["folder"]):
            util.write_text(self.script_path, startup_script(*self.bin, self.cfg), make_backup=False)
            self.script_path.chmod(self.script_path.stat().st_mode | stat.S_IXUSR)
            self.model.set_autostart(cmd, True)
            hint = "" if self.model.b.hook_installed() else " Add Hyprtune's settings file to your Hyprland config on the Overview page for it to run at startup."
            self.message.emit("Saved. The wallpaper will be set when Hyprland starts." + hint, False)
        else:
            self.model.set_autostart(cmd, False)
            self.message.emit("Saved.", False)
